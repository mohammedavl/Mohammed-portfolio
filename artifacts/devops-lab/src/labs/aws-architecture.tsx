import { useState } from 'react';
import { LabFrame, Panel, Field, Pill, Stat } from '@/components/lab-kit';

const REGIONS: Record<string, string[]> = {
  'us-east-1': ['a', 'b', 'c', 'd', 'f'],
  'eu-west-1': ['a', 'b', 'c'],
  'eu-central-1': ['a', 'b', 'c'],
  'ap-southeast-2': ['a', 'b', 'c'],
  'sa-east-1': ['a', 'b', 'c'],
};
const SIZES = ['t3.small', 't3.medium', 'm6i.large', 'c6i.xlarge'];
const D = { region: 'eu-west-1', replicas: 4, azCount: 3, size: 't3.medium', db: true };

export default function AwsArchitecture() {
  const [s, setS] = useState(D);
  const zones = REGIONS[s.region].slice(0, Math.min(s.azCount, REGIONS[s.region].length)).map((z) => s.region + z);
  const perAz = zones.map((_, i) => Math.floor(s.replicas / zones.length) + (i < s.replicas % zones.length ? 1 : 0));
  const minSize = Math.max(1, s.replicas - Math.max(...perAz));
  const yaml = `AWSTemplateFormatVersion: '2010-09-09'
Description: Web tier in ${s.region} - ${s.replicas} x ${s.size} across ${zones.length} AZs (generated by DevOps Lab)
Parameters:
  LatestAmiId:
    Type: AWS::SSM::Parameter::Value<AWS::EC2::Image::Id>
    Default: /aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64
Resources:
  Vpc:
    Type: AWS::EC2::VPC
    Properties: { CidrBlock: 10.20.0.0/16, EnableDnsHostnames: true }
  Igw: { Type: AWS::EC2::InternetGateway }
  IgwAttach:
    Type: AWS::EC2::VPCGatewayAttachment
    Properties: { VpcId: !Ref Vpc, InternetGatewayId: !Ref Igw }
${zones
  .map(
    (z, i) => `  Public${i}:
    Type: AWS::EC2::Subnet
    Properties: { VpcId: !Ref Vpc, AvailabilityZone: ${z}, CidrBlock: 10.20.${i}.0/24, MapPublicIpOnLaunch: true }
  Private${i}:
    Type: AWS::EC2::Subnet
    Properties: { VpcId: !Ref Vpc, AvailabilityZone: ${z}, CidrBlock: 10.20.${100 + i}.0/24 }`,
  )
  .join('\n')}
  AlbSg:
    Type: AWS::EC2::SecurityGroup
    Properties:
      GroupDescription: ALB ingress
      VpcId: !Ref Vpc
      SecurityGroupIngress: [{ IpProtocol: tcp, FromPort: 80, ToPort: 80, CidrIp: 0.0.0.0/0 }]
  AppSg:
    Type: AWS::EC2::SecurityGroup
    Properties:
      GroupDescription: App from ALB only
      VpcId: !Ref Vpc
      SecurityGroupIngress: [{ IpProtocol: tcp, FromPort: 8080, ToPort: 8080, SourceSecurityGroupId: !Ref AlbSg }]
  Alb:
    Type: AWS::ElasticLoadBalancingV2::LoadBalancer
    Properties:
      Subnets: [${zones.map((_, i) => `!Ref Public${i}`).join(', ')}]
      SecurityGroups: [!Ref AlbSg]
  TargetGroup:
    Type: AWS::ElasticLoadBalancingV2::TargetGroup
    Properties: { VpcId: !Ref Vpc, Port: 8080, Protocol: HTTP, HealthCheckPath: /healthz }
  Listener:
    Type: AWS::ElasticLoadBalancingV2::Listener
    Properties:
      LoadBalancerArn: !Ref Alb
      Port: 80
      Protocol: HTTP
      DefaultActions: [{ Type: forward, TargetGroupArn: !Ref TargetGroup }]
  LaunchTemplate:
    Type: AWS::EC2::LaunchTemplate
    Properties:
      LaunchTemplateData:
        ImageId: !Ref LatestAmiId
        InstanceType: ${s.size}
        SecurityGroupIds: [!Ref AppSg]
        MetadataOptions: { HttpTokens: required }
  Asg:
    Type: AWS::AutoScaling::AutoScalingGroup
    Properties:
      MinSize: '${minSize}'
      MaxSize: '${s.replicas * 2}'
      DesiredCapacity: '${s.replicas}'
      VPCZoneIdentifier: [${zones.map((_, i) => `!Ref Private${i}`).join(', ')}]
      TargetGroupARNs: [!Ref TargetGroup]
      HealthCheckType: ELB
      LaunchTemplate: { LaunchTemplateId: !Ref LaunchTemplate, Version: !GetAtt LaunchTemplate.LatestVersionNumber }
${
  s.db
    ? `  DbSubnets:
    Type: AWS::RDS::DBSubnetGroup
    Properties:
      DBSubnetGroupDescription: private
      SubnetIds: [${zones.map((_, i) => `!Ref Private${i}`).join(', ')}]
  Database:
    Type: AWS::RDS::DBInstance
    DeletionPolicy: Snapshot
    Properties:
      Engine: postgres
      DBInstanceClass: db.t4g.medium
      AllocatedStorage: '50'
      MultiAZ: true
      DBSubnetGroupName: !Ref DbSubnets
      MasterUsername: app
      ManageMasterUserPassword: true
`
    : ''
}Outputs:
  Endpoint: { Value: !GetAtt Alb.DNSName }
`;
  const warn = zones.length < 2 ? 'Single AZ: one zone outage takes the whole service down.' : s.replicas < zones.length ? 'Fewer replicas than AZs: some zones receive no capacity.' : null;

  return (
    <LabFrame mode="tool" onReset={() => setS(D)} files={[{ name: 'template.yaml', content: yaml }]}>
      <div className="grid gap-4 lg:grid-cols-[280px_1fr]">
        <Panel title="Inputs">
          <div className="space-y-3">
            <Field label="Region">
              <select className="lab-input" value={s.region} onChange={(e) => setS({ ...s, region: e.target.value })} data-testid="select-region">
                {Object.keys(REGIONS).map((r) => <option key={r}>{r}</option>)}
              </select>
            </Field>
            <Field label={`Replicas: ${s.replicas}`}>
              <input type="range" min={1} max={12} value={s.replicas} onChange={(e) => setS({ ...s, replicas: +e.target.value })} className="w-full accent-[hsl(var(--primary))]" data-testid="input-replicas" />
            </Field>
            <Field label={`Availability zones: ${zones.length}`}>
              <input type="range" min={1} max={REGIONS[s.region].length} value={Math.min(s.azCount, REGIONS[s.region].length)} onChange={(e) => setS({ ...s, azCount: +e.target.value })} className="w-full accent-[hsl(var(--primary))]" data-testid="input-az" />
            </Field>
            <Field label="Instance type">
              <select className="lab-input" value={s.size} onChange={(e) => setS({ ...s, size: e.target.value })} data-testid="select-size">
                {SIZES.map((r) => <option key={r}>{r}</option>)}
              </select>
            </Field>
            <label className="flex items-center gap-2 text-sm">
              <input type="checkbox" checked={s.db} onChange={(e) => setS({ ...s, db: e.target.checked })} data-testid="checkbox-db" /> Multi-AZ PostgreSQL tier
            </label>
          </div>
        </Panel>
        <Panel title="Topology" aside={warn ? <Pill tone="warn">{warn}</Pill> : <Pill tone="ok">AZ-resilient</Pill>}>
          <div className="mb-4 grid grid-cols-3 gap-3">
            <Stat label="Desired" value={s.replicas} />
            <Stat label="MinSize" value={minSize} />
            <Stat label="Subnets" value={zones.length * 2} />
          </div>
          <div className="mx-auto mb-3 w-fit border border-foreground bg-secondary px-4 py-1.5 font-mono text-xs text-secondary-foreground">ALB :80</div>
          <div className="grid gap-2" style={{ gridTemplateColumns: `repeat(${zones.length}, minmax(0,1fr))` }}>
            {zones.map((z, i) => (
              <div key={z} className="border border-dashed border-foreground/40 p-2" data-testid={`az-${z}`}>
                <div className="lab-label mb-2">{z}</div>
                <div className="flex flex-wrap gap-1">
                  {Array.from({ length: perAz[i] }).map((_, k) => (
                    <div key={k} className="rise border border-accent bg-accent/15 px-1.5 py-1 font-mono text-[10px] text-accent" style={{ animationDelay: `${k * 40}ms` }}>{s.size}</div>
                  ))}
                  {perAz[i] === 0 && <span className="font-mono text-[10px] text-muted-foreground">empty</span>}
                </div>
              </div>
            ))}
          </div>
          {s.db && <div className="mx-auto mt-3 w-fit border border-primary bg-primary/10 px-4 py-1.5 font-mono text-xs text-primary">RDS postgres Multi-AZ</div>}
        </Panel>
      </div>
    </LabFrame>
  );
}
